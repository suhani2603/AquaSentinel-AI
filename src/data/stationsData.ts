/**
 * Generates 7 days of 6-hour timestamp observations (28 intervals).
 */
function generate7DayHistory(
  city: string,
  river: string,
  stationName: string,
  baseFlow: number,
  baseStage: number,
  baseRain: number,
  damName: string | null,
  baseDamRelease: number | null,
  baseReservoirLevel: number | null,
  warnStage: number,
  dangerStage: number,
  trendMultiplier: number = 1.0,
  surgeAtEnd: boolean = false
): HydrologicalObservation[] {
  const observations: HydrologicalObservation[] = [];
  const days = ['Day -6', 'Day -5', 'Day -4', 'Day -3', 'Day -2', 'Yesterday', 'Today'];
  const times = ['00:00', '06:00', '12:00', '18:00'];

  days.forEach((dayStr, dIdx) => {
    times.forEach((timeStr, tIdx) => {
      const stepIndex = dIdx * 4 + tIdx;
      const isLastStep = stepIndex === 27;
      const isSecondToLast = stepIndex === 26;

      // Realistic meteorological and hydrological diurnal curve
      const dayFactor = Math.sin((stepIndex / 28) * Math.PI) * trendMultiplier;
      const noise = (Math.sin(stepIndex * 1.7) * 0.05 + 1);

      let flowVal = Math.round(baseFlow * (0.85 + dayFactor * 0.3) * noise);
      let stageVal = Number((baseStage + (flowVal - baseFlow) * 0.0006).toFixed(2));
      let rainVal = Math.max(0, Number((baseRain * (0.5 + Math.sin(stepIndex * 0.8) * 0.5)).toFixed(1)));
      let damRel = baseDamRelease !== null ? Math.round(baseDamRelease * (0.9 + dayFactor * 0.2)) : null;

      if (surgeAtEnd && (isLastStep || isSecondToLast)) {
        if (isLastStep) {
          flowVal = Math.round(baseFlow * 1.714);
          stageVal = Number((baseStage + 1.25).toFixed(2));
          rainVal = Number((baseRain * 2.8).toFixed(1));
          if (damRel !== null) damRel = Math.round(baseDamRelease * 1.82);
        } else {
          flowVal = Math.round(baseFlow * 1.15);
          stageVal = Number((baseStage + 0.35).toFixed(2));
        }
      }

      const prevFlow = observations.length > 0 ? observations[observations.length - 1].river_flow_m3s || flowVal : flowVal;
      const rateOfChange = prevFlow > 0 ? Number((((flowVal - prevFlow) / prevFlow) * 100).toFixed(1)) : 0;

      const hoursAgo = Math.max(0, (6 - dIdx) * 24 + (18 - parseInt(timeStr.slice(0, 2), 10)));
      const obsDate = new Date(Date.now() - hoursAgo * 3600 * 1000);
      const obsTimestamp = obsDate.toISOString();
      const displayTime = obsDate.toLocaleDateString('en-US', {
        month: 'short',
        day: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
        hour12: false
      });

      observations.push({
        timestamp: obsTimestamp,
        displayTime: displayTime,
        city,
        river,
        monitoring_station: stationName,
        river_flow_m3s: flowVal,
        water_level_m: stageVal,
        rainfall_mm: rainVal,
        dam_name: damName,
        dam_release_m3s: damRel,
        reservoir_level_m: baseReservoirLevel,
        warning_threshold: warnStage,
        danger_threshold: dangerStage,
        rateOfChangePercent: rateOfChange,
        isRapidIncrease: rateOfChange >= 25
      });
    });
  });

  return observations;
}

